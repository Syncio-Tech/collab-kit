import { join } from "node:path";
import { Config } from "./config.js";
import { listTickets, convDir } from "./ticket.js";

export function renderIndex(root: string, cfg: Config): string {
  const team = (cfg.parties["spec-owner"].members ?? []).length > 1;     // the assignee column only exists for a spec-side team
  const rows = listTickets(root, cfg).map((t) => {
    const d = t.doc.data;
    const title = String(d.title ?? "").replace(/\|/g, "\\|");
    const esc = (Array.isArray(d.escalations) ? d.escalations : []).some((e: any) => !e.resolved_at) ? " (escalated)" : "";
    const who = team ? ` ${d.assignee ?? "-"} |` : "";
    return `| [${t.id}](${t.id}/ticket.md) | ${title} | ${d.level ?? ""} | ${d.state ?? ""}${esc} |${who} ${d.waiting_for ?? ""} | ${t.turns.length} | ${d.updated_at ?? d.opened_at ?? ""} |`;
  });
  const head = team ? ["| id | title | level | state | assignee | waiting_for | turns | updated |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    : ["| id | title | level | state | waiting_for | turns | updated |", "| --- | --- | --- | --- | --- | --- | --- |"];
  return [
    "# INDEX",
    "",
    "<!-- generated by `collab index` - do not edit by hand -->",
    "",
    ...head,
    ...rows,
    "",
  ].join("\n");
}

export function indexPath(root: string, cfg: Config): string { return join(convDir(root, cfg), "INDEX.md"); }
